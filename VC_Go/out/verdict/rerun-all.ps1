# -- 2. parsers over the time-series table of market-sim output
function Parse-Run($o) {
  # Time-series rows are the only table rows in market-sim output with EXACTLY
  # 9 whitespace-separated numeric tokens (tick pop levels power cash tax op debt cap);
  # calibration rows have 4, layout rows 4, flow rows 8, margin rows 12.
  $res = @()
  foreach ($ln in ($o -split "`n")) {
    $t = @($ln.Trim() -split '\s+' | Where-Object { $_ -ne '' })
    if ($t.Count -ne 9) { continue }
    $ok = $true
    foreach ($tok in $t) { $d = 0.0; if (-not [double]::TryParse($tok, [ref]$d)) { $ok = $false; break } }
    if (-not $ok) { continue }
    $res += New-Object psobject -Property @{
      Tick    = [int]$t[0]
      Pop     = [double]$t[1]
      Levels  = [double]$t[2]
      Power   = [double]$t[3]
      GovCash = [double]$t[4]
    }
  }
  return $res
}
function Run-Sim($a) { return (& $sim @a 2>&1 | Out-String) }
function Last-Row($a) { $r = Parse-Run (Run-Sim $a); return $r[$r.Count - 1] }

# -- 3. pure-arithmetic probes (node)
$probeTxt = "# probe rerun (node = Electron RUN_AS_NODE)`r`n"
foreach ($p in @('contract_consistency_probe.js', 'survival_condition_probe.js')) {
  $o = (& $nodeExe (Join-Path $root "tools\$p") 2>&1 | Out-String)
  $n = ($o -split "`n").Count
  $probeTxt += "  $p : exit=$LASTEXITCODE lines=$n`r`n"
}
Add-Text (Join-Path $outv 'RERUN-ENV.txt') $probeTxt

# -- 4. tax sweep: 600 ticks x 8 tax rates + material-balance layout + privatize
$sweep = Join-Path $outv 'sim-600-tax-sweep.txt'
Set-Text $sweep ("# 600-tick tax sweep and layout arms (REGENERATED; full stdout per arm)`r`n# population 10,000,000; each arm preceded by its exact command`r`n")
$arms = @(
  @{ name = 'default-5   t=0.00'; a = @('-ticks','600','-tax','0.00') },
  @{ name = 'default-5   t=0.10'; a = @('-ticks','600','-tax','0.10') },
  @{ name = 'default-5   t=0.20'; a = @('-ticks','600','-tax','0.20') },
  @{ name = 'default-5   t=0.40'; a = @('-ticks','600','-tax','0.40') },
  @{ name = 'default-5   t=0.70'; a = @('-ticks','600','-tax','0.70') },
  @{ name = 'default-5   t=1.00'; a = @('-ticks','600','-tax','1.00') },
  @{ name = 'default-5   t=1.50'; a = @('-ticks','600','-tax','1.50') },
  @{ name = 'default-5   t=2.00'; a = @('-ticks','600','-tax','2.00') },
  @{ name = 'matbalance  t=0.00'; a = @('-ticks','600','-tax','0.00','-init-level','0') },
  @{ name = 'matbalance  t=0.10'; a = @('-ticks','600','-tax','0.10','-init-level','0') },
  @{ name = 'matbal+priv t=0.10'; a = @('-ticks','600','-tax','0.10','-init-level','0','-privatize') }
)
$sumRows = @()
foreach ($arm in $arms) {
  $cmd = 'market-sim.exe ' + ($arm.a -join ' ')
  $o = Run-Sim $arm.a
  Add-Text $sweep ((HR "# $cmd") + "`r`n" + $o)
  $rows = Parse-Run $o
  # initial layout total = the only 2-token line whose second token is numeric
  # (the "total <n>" row closing the opening-layout table)
  $lv0 = ''
  foreach ($ln in ($o -split "`n")) {
    $t = @($ln.Trim() -split '\s+' | Where-Object { $_ -ne '' })
    if ($t.Count -eq 2 -and $t[1] -match '^[\d.]+$' -and $t[0] -notmatch '^[\d.]+$') { $lv0 = $t[1] }
  }
  $last = $rows[$rows.Count - 1]
  $sumRows += New-Object psobject -Property @{
    Arm = $arm.name; Lv0 = $lv0; Tick = $last.Tick; Levels = $last.Levels
    Pop = $last.Pop; GovCash = $last.GovCash
  }
}
$tbl = (HR '# summary (parsed from the outputs above)') + "`r`n"
$tbl += ("{0,-16} {1,6} {2,6} {3,10} {4,14} {5,18}`r`n" -f 'arm','lv0','tick','levels','pop','govcash')
foreach ($r in $sumRows) {
  $tbl += ("{0,-16} {1,6} {2,6} {3,10} {4,14} {5,18}`r`n" -f $r.Arm, $r.Lv0, $r.Tick, $r.Levels, $r.Pop, $r.GovCash)
}
Add-Text $sweep $tbl

# -- 5. contract-mandated long runs
