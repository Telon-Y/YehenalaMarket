Set-Text (Join-Path $outv 'sim-3000-init-level-0.txt') ((HR '# market-sim.exe -ticks 3000 -init-level 0   (material-balance layout)') + "`r`n" + (Run-Sim @('-ticks','3000','-init-level','0')))

